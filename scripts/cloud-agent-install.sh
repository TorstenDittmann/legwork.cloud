#!/usr/bin/env bash
# Idempotent bootstrap for Cursor Cloud Agent environments.
# Installs the pinned Bun toolchain, workspace dependencies, a local dev .env,
# and the local SQLite database. Safe to run repeatedly.
set -euo pipefail

cd "$(dirname "$0")/.."

BUN_VERSION="1.4.0"
export BUN_INSTALL="${BUN_INSTALL:-$HOME/.bun}"
export PATH="$BUN_INSTALL/bin:$PATH"

if ! command -v bun >/dev/null 2>&1 || [ "$(bun --version 2>/dev/null || true)" != "$BUN_VERSION" ]; then
	echo "Installing Bun ${BUN_VERSION}..."
	curl -fsSL https://bun.sh/install | bash -s "bun-v${BUN_VERSION}"
fi
export PATH="$BUN_INSTALL/bin:$PATH"
bun --version

echo "Installing workspace dependencies..."
bun install --frozen-lockfile

# Provide a local development .env so the web app boots for public pages.
# These are non-secret local placeholders; real integrations (WorkOS, GitHub
# App, OpenRouter, Railway, Dodo, Resend) require credentials supplied as
# Cursor secrets / environment variables.
if [ ! -f .env ]; then
	echo "Creating local .env with generated local-only keys..."
	ENC_KEY="$(bun -e 'console.log(Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64"))')"
	COOKIE="$(bun -e 'console.log(Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64url"))')"
	cat > .env <<EOF
# Local development defaults generated by scripts/cloud-agent-install.sh.
# Real integrations require credentials supplied as environment variables/secrets.
DATABASE_URL=file:local.db
DATABASE_AUTH_TOKEN=
APP_URL=http://localhost:5173
DATA_ENCRYPTION_KEY=${ENC_KEY}
LOG_LEVEL=info

# WorkOS AuthKit (local placeholders; real values required for sign-in flows).
WORKOS_CLIENT_ID=client_local_dev
WORKOS_API_KEY=sk_local_dev
WORKOS_COOKIE_PASSWORD=${COOKIE}
WORKOS_REDIRECT_URI=http://localhost:5173/auth/callback

METRICS_TOKEN=local-metrics-token

# Billing (web only).
DODO_PAYMENTS_API_KEY=
DODO_PAYMENTS_WEBHOOK_KEY=
DODO_PAYMENTS_ENVIRONMENT=test_mode
DODO_PAYMENTS_RETURN_URL=http://localhost:5173/checkout/success
DODO_PAYMENTS_TEAM_MONTHLY_PRODUCT_ID=
DODO_PAYMENTS_TEAM_ANNUAL_PRODUCT_ID=
DODO_PAYMENTS_SCALE_MONTHLY_PRODUCT_ID=
DODO_PAYMENTS_SCALE_ANNUAL_PRODUCT_ID=

# GitHub App (worker).
GITHUB_APP_ID=000000
GITHUB_APP_SLUG=legwork-local
GITHUB_APP_PRIVATE_KEY=
GITHUB_WEBHOOK_SECRET=local-webhook-secret
GITHUB_INSTALLATION_STATE_SECRET=local-installation-state-secret

# Worker.
OPENROUTER_API_KEY=sk-or-local-dev
OPENROUTER_MODEL=deepseek/deepseek-v4-flash-0731
LANGCHAIN_TRACING_V2=false
LANGSMITH_TRACING=false
RAILWAY_TOKEN=
RAILWAY_ENVIRONMENT_ID=
SANDBOX_COMMAND_EXECUTION=false
SANDBOX_CAPABILITY_PROBE_PASSED=false
WORKER_CONCURRENCY=5
SHUTDOWN_GRACE_MS=25000

# Notifications (worker only).
RESEND_API_KEY=
RESEND_FROM_ADDRESS=
EOF
else
	echo ".env already exists; leaving it untouched."
fi

echo "Applying database migrations..."
bun run db:migrate

echo "Cloud Agent install complete."
